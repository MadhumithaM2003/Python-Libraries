"""Exercise 8: Subject-wise Marks Comparison

subjects = ["Python", "Java", "SQL", "ML", "Statistics"] student1 = [85, 78, 90, 88, 75]

student2 = [80, 82, 85, 92, 80]
"""

import numpy as np

subjects = ["Python", "Java", "SQL", "ML", "Statistics"]

student1 = [85, 78, 90, 88, 75]
student2 = [80, 82, 85, 92, 80]

x = np.arange(len(subjects))
width = 0.35

plt.bar(x - width/2, student1, width,label='Student 1', color='teal')

plt.bar(x + width/2, student2, width,label='Student 2', color='red')

plt.title("Subject-wise Marks Comparison")
plt.xlabel("Subjects")
plt.ylabel("Marks")
plt.xticks(x, subjects)
plt.legend()
plt.show()
plt.savefig("subject_comparison.png")

