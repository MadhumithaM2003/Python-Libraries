"""SECTION C – DATA CLEANING AND TRANSFORMATION

Create a DataFrame (NaN as a missing value.)
"""

import numpy as np

data = {
'Name': ['Arun', 'Priya', 'Karthik', 'Divya', 'Rahul'],
'Age': [25, np.nan, 28, 24, np.nan],
'Salary': [30000, 35000, np.nan, 40000, 32000],
'Department': ['IT', 'HR', 'IT', np.nan, 'HR']
}
df = pd.DataFrame(data)
print(df)

"""Display the missing-value count for every column."""

print(df.isnull().sum())

"""Find the total number of missing values in the DataFrame."""

print(df.isnull().sum().sum())

"""Replace missing Age values with the mean Age."""

df['Age'] = df['Age'].fillna(df['Age'].mean())
print(df)

"""Replace missing Salary values with the median Salary."""

df['Salary'] = df['Salary'].fillna(df['Salary'].median())
print(df)

"""Remove rows where Department is missing and display the cleaned DataFrame."""

df = df.dropna(subset=['Department'])
print(df)

"""SECTION D – GROUPING AND AGGREGATION"""

data = {
'Employee': ['Arun', 'Priya', 'Karthik', 'Divya', 'Rahul', 'Meena'],
'Department': ['IT', 'HR', 'IT', 'HR', 'Finance', 'Finance'],
'Salary': [35000, 30000, 45000, 40000, 50000, 55000],
'Experience': [2, 3, 5, 4, 6, 7]
}
df = pd.DataFrame(data)
print(df)

"""Calculate the average salary for each department."""

print(df.groupby('Department')['Salary'].mean())

"""Find the maximum salary in each department."""

print(df.groupby('Department')['Salary'].max())

"""Count the number of employees in each department."""

print(df.groupby('Department')['Employee'].count())

"""Calculate the average experience for each department."""

print(df.groupby('Department')['Experience'].mean())

"""Sort departments by average salary in descending order."""

avg_sal = df.groupby('Department')['Salary'].mean().sort_values(ascending=False)
print(avg_sal)

"""SECTION E – ADVANCED PANDAS OPERATIONS

Create a new column named Annual_Salary by multiplying monthly Salary by 12.
"""

df['Annual_Salary'] = df['Salary'] * 12
print(df)

"""Rename the Employee column as Employee_Name."""

df = df.rename(columns={'Employee': 'Employee_Name'})
print(df)

"""Sort all employee records by Salary in descending order."""

df = df.sort_values(['Salary'], ascending=False)
print(df)

"""Find the second-highest distinct salary using Pandas operations."""

salary = df['Salary'].drop_duplicates().sort_values(ascending=False)
print(salary.iloc[1])

"""Export the final DataFrame to a CSV file named employee_analysis.csv without writing the DataFrame index."""

df.to_csv('employee_analysis.csv', index=False)