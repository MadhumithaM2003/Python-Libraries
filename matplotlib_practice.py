import matplotlib.pyplot as plt

students = ["A", "B", "C", "D", "E"]
marks = [75, 82, 68, 90, 78]

plt.bar(students, marks)
plt.title("Student Marks - Bar Chart")
plt.xlabel("Students")
plt.ylabel("Marks")
plt.grid()
plt.show()

plt.plot(students, marks, marker='o')
plt.title("Student Marks - Line Plot")
plt.xlabel("Students")
plt.ylabel("Marks")
plt.grid()
plt.show()

plt.savefig("students_marks_chart.png")